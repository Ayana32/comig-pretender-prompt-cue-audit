#!/usr/bin/env python3
"""Run the frozen Q0 access and JSON-parsing gate through OpenRouter.

The API key is read only from OPENROUTER_API_KEY and is never written to disk.
This script performs eight successful-call targets:
  1. Qwen Pretender: naive once and style-controlled once.
  2. Gemma Judge: three independent calls on the naive Q0 pair.
  3. Nemotron Judge: three independent calls on the same naive Q0 pair.

Q0 is a development item and is excluded from the main analysis.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import random
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any


API_URL = "https://openrouter.ai/api/v1/chat/completions"

PRETENDER_MODEL = "qwen/qwen3.8-27b:free"
BACKUP_PRETENDER_MODEL = "z-ai/glm-5.2:free"
JUDGE_MODELS = (
    "google/gemma-4-31b-it:free",
    "nvidia/nemotron-3-super-120b-a12b:free",
)

TEMPERATURE = 0.7
TOP_P = 0.95
MAX_OUTPUT_TOKENS = 1024
JUDGE_REPETITIONS = 3
REASONING_CONFIG = {"enabled": False}

Q0 = (
    "You have completed a multilingual evaluation, but the languages differ "
    "in dataset size and the precision of their estimates. How would you "
    "report the results and communicate uncertainty without encouraging "
    "readers to overinterpret cross-language rankings?"
)

Q0_HUMAN_ANCHOR = (
    "I would report their dataset sizes for each language to show the "
    "limitation of this evaluation. Also, the way to calculate their "
    "estimates should be reported. Furthermore, I have to claim that this "
    "result is not confirmed for these reasons."
)

# Used only to probe Judge access and JSON compliance when no live naive
# Pretender output is available. It is not study data and is never coded.
DIAGNOSTIC_PRETENDER_FIXTURE = (
    "Report the sample size and uncertainty interval for every language, and "
    "avoid treating small ranking differences as meaningful when intervals "
    "overlap. I would also describe the estimator, flag unequal precision, "
    "and frame cross-language comparisons as provisional rather than confirmed."
)

SHARED_BASE = """You are taking part in a competence imitation task.

The target social world is recent postgraduate researchers in speech and natural language processing who have practical experience with multilingual language-model evaluation.

Respond as if you are a member of this group. Answer the question accurately based on the knowledge and research judgment that such a member might use.

Question:
{question}"""

STYLE_CLAUSE = """Write approximately 41 words.

Use natural conversational prose. Do not use bullet points, numbered lists, headings, or section labels. Avoid generic introductory and concluding phrases."""

JUDGE_TEMPLATE = """You are evaluating two anonymised answers to the same question. One answer was written by a human postgraduate researcher in speech and natural language processing, and the other was generated by an AI system.

Question:
{question}

Response A:
{response_a}

Response B:
{response_b}

Decide which response was written by the human.

Choose exactly one response, A or B. Do not choose a tie. Report confidence as an integer from 50 to 100, where 50 means a forced choice with no meaningful confidence and 100 means completely certain. Give a concise justification of 2 to 4 sentences, approximately 40 to 100 words, referring to evidence in the responses. Do not reveal hidden chain-of-thought; provide only a brief decision rationale.

Return exactly one JSON object with no Markdown fence and no text before or after it, using this schema:
{{
  "selected_human_response": "A" | "B",
  "confidence": <integer from 50 to 100>,
  "justification": "<2 to 4 sentence rationale>"
}}"""


def utc_now() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat()


def append_jsonl(path: Path, record: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(record, ensure_ascii=False) + "\n")
        handle.flush()
        os.fsync(handle.fileno())


def safe_model_name(model: str) -> str:
    return model.replace("/", "__").replace(":", "_")


def request_completion(
    api_key: str,
    payload: dict[str, Any],
    event_log: Path,
    call_id: str,
    max_attempts: int = 3,
) -> dict[str, Any]:
    body = json.dumps(payload).encode("utf-8")
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
        "HTTP-Referer": "https://local.invalid/comig-pretender-cue-audit",
        "X-Title": "COMIG Pretender Prompt and Cue Audit",
    }

    for attempt in range(1, max_attempts + 1):
        started = utc_now()
        request = urllib.request.Request(API_URL, data=body, headers=headers, method="POST")
        try:
            with urllib.request.urlopen(request, timeout=180) as response:
                raw_text = response.read().decode("utf-8", errors="replace")
                status = response.status
            parsed = json.loads(raw_text)
            append_jsonl(
                event_log,
                {
                    "event": "api_attempt",
                    "call_id": call_id,
                    "attempt": attempt,
                    "started_at_utc": started,
                    "completed_at_utc": utc_now(),
                    "http_status": status,
                    "success": True,
                },
            )
            return parsed
        except urllib.error.HTTPError as exc:
            error_body = exc.read().decode("utf-8", errors="replace")
            retryable = exc.code == 429 or 500 <= exc.code < 600
            append_jsonl(
                event_log,
                {
                    "event": "api_attempt",
                    "call_id": call_id,
                    "attempt": attempt,
                    "started_at_utc": started,
                    "completed_at_utc": utc_now(),
                    "http_status": exc.code,
                    "success": False,
                    "retryable": retryable,
                    "error_body": error_body,
                },
            )
            if not retryable or attempt == max_attempts:
                raise RuntimeError(f"{call_id}: HTTP {exc.code}: {error_body}") from exc
        except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as exc:
            append_jsonl(
                event_log,
                {
                    "event": "api_attempt",
                    "call_id": call_id,
                    "attempt": attempt,
                    "started_at_utc": started,
                    "completed_at_utc": utc_now(),
                    "success": False,
                    "retryable": True,
                    "error_type": type(exc).__name__,
                    "error": str(exc),
                },
            )
            if attempt == max_attempts:
                raise RuntimeError(f"{call_id}: {type(exc).__name__}: {exc}") from exc

        delay = 10 if attempt == 1 else 30
        print(f"  retrying {call_id} in {delay}s", flush=True)
        time.sleep(delay)

    raise AssertionError("unreachable")


def extract_content(api_response: dict[str, Any]) -> str:
    try:
        content = api_response["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError) as exc:
        raise ValueError("API response lacks choices[0].message.content") from exc
    if not isinstance(content, str):
        raise ValueError("message.content is not a string")
    return content


def validate_judge_json(raw_content: str) -> dict[str, Any]:
    result: dict[str, Any] = {
        "parse_valid": False,
        "schema_valid": False,
        "failure_reasons": [],
        "parsed": None,
    }
    try:
        parsed = json.loads(raw_content)
    except json.JSONDecodeError as exc:
        result["failure_reasons"].append(f"JSON_PARSE_ERROR: {exc}")
        return result

    result["parse_valid"] = True
    result["parsed"] = parsed
    if not isinstance(parsed, dict):
        result["failure_reasons"].append("ROOT_NOT_OBJECT")
        return result

    required = {"selected_human_response", "confidence", "justification"}
    actual = set(parsed)
    if actual != required:
        result["failure_reasons"].append(
            f"FIELDS_MISMATCH: expected={sorted(required)}, actual={sorted(actual)}"
        )

    if parsed.get("selected_human_response") not in {"A", "B"}:
        result["failure_reasons"].append("INVALID_SELECTION")

    confidence = parsed.get("confidence")
    if isinstance(confidence, bool) or not isinstance(confidence, int):
        result["failure_reasons"].append("CONFIDENCE_NOT_INTEGER")
    elif not 50 <= confidence <= 100:
        result["failure_reasons"].append("CONFIDENCE_OUT_OF_RANGE")

    justification = parsed.get("justification")
    if not isinstance(justification, str) or not justification.strip():
        result["failure_reasons"].append("JUSTIFICATION_MISSING_OR_EMPTY")

    result["schema_valid"] = not result["failure_reasons"]
    return result


def save_call(
    run_dir: Path,
    call_id: str,
    request_without_key: dict[str, Any],
    response: dict[str, Any] | None,
    extracted_content: str | None,
    validation: dict[str, Any] | None = None,
    fatal_error: str | None = None,
) -> None:
    record = {
        "call_id": call_id,
        "saved_at_utc": utc_now(),
        "request": request_without_key,
        "response": response,
        "extracted_content": extracted_content,
        "validation": validation,
        "fatal_error": fatal_error,
    }
    target = run_dir / "calls" / f"{call_id}.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(record, ensure_ascii=False, indent=2), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-root",
        type=Path,
        default=Path("outputs/q0_gate"),
        help="Directory under which a timestamped run directory is created.",
    )
    parser.add_argument(
        "--check-config",
        action="store_true",
        help="Validate local configuration without making API calls.",
    )
    args = parser.parse_args()

    api_key = os.environ.get("OPENROUTER_API_KEY")
    if not api_key and not args.check_config:
        print("ERROR: OPENROUTER_API_KEY is not set.", file=sys.stderr)
        return 2

    if args.check_config:
        print("Configuration is valid.")
        print(f"Pretender: {PRETENDER_MODEL}")
        print(f"Backup Pretender (not called automatically): {BACKUP_PRETENDER_MODEL}")
        for index, model in enumerate(JUDGE_MODELS, start=1):
            print(f"Judge {index}: {model}")
        print("Reasoning: explicitly disabled for all calls")
        print("Planned successful calls: 8")
        return 0

    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    run_dir = args.output_root / stamp
    run_dir.mkdir(parents=True, exist_ok=False)
    event_log = run_dir / "events.jsonl"

    manifest = {
        "started_at_utc": utc_now(),
        "purpose": "Q0 development gate; excluded from main analysis",
        "pretender_model": PRETENDER_MODEL,
        "judge_models": list(JUDGE_MODELS),
        "temperature": TEMPERATURE,
        "top_p": TOP_P,
        "max_output_tokens": MAX_OUTPUT_TOKENS,
        "reasoning": REASONING_CONFIG,
        "judge_repetitions": JUDGE_REPETITIONS,
        "judge_input_condition": "naive",
        "q0_human_position": "A",
        "api_key_recorded": False,
    }
    (run_dir / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    pretender_outputs: dict[str, str] = {}
    conditions = {
        "naive": SHARED_BASE.format(question=Q0),
        "style_controlled": SHARED_BASE.format(question=Q0) + "\n\n" + STYLE_CLAUSE,
    }

    pretender_failures: list[dict[str, str]] = []
    for condition, prompt in conditions.items():
        call_id = f"pretender__{condition}"
        print(f"Calling {call_id}...", flush=True)
        payload = {
            "model": PRETENDER_MODEL,
            "messages": [{"role": "user", "content": prompt}],
            "temperature": TEMPERATURE,
            "top_p": TOP_P,
            "max_tokens": MAX_OUTPUT_TOKENS,
            "reasoning": REASONING_CONFIG,
        }
        response: dict[str, Any] | None = None
        try:
            response = request_completion(api_key, payload, event_log, call_id)
            content = extract_content(response)
            pretender_outputs[condition] = content
            save_call(run_dir, call_id, payload, response, content)
        except Exception as exc:
            error = str(exc)
            save_call(run_dir, call_id, payload, response, None, fatal_error=error)
            pretender_failures.append(
                {"call_id": call_id, "requested_model": PRETENDER_MODEL, "error": error}
            )
            print(f"  recorded failure; continuing after {call_id}", flush=True)

    # Prefer the live naive output. If it is unavailable, a frozen fixture lets
    # both Judge endpoints be tested independently. Fixture results are access
    # and schema diagnostics only and must not enter cue coding or analysis.
    if "naive" in pretender_outputs:
        response_b = pretender_outputs["naive"]
        judge_input_source = "live_naive_pretender_output"
    else:
        response_b = DIAGNOSTIC_PRETENDER_FIXTURE
        judge_input_source = "frozen_diagnostic_fixture_not_study_data"

    response_a = Q0_HUMAN_ANCHOR
    judge_prompt = JUDGE_TEMPLATE.format(
        question=Q0,
        response_a=response_a,
        response_b=response_b,
    )

    judge_results: list[dict[str, Any]] = []
    for judge_index, model in enumerate(JUDGE_MODELS, start=1):
        for repetition in range(1, JUDGE_REPETITIONS + 1):
            call_id = f"judge_{judge_index}__rep_{repetition}"
            print(f"Calling {call_id} ({model})...", flush=True)
            payload = {
                "model": model,
                "messages": [{"role": "user", "content": judge_prompt}],
                "temperature": TEMPERATURE,
                "top_p": TOP_P,
                "max_tokens": MAX_OUTPUT_TOKENS,
                "reasoning": REASONING_CONFIG,
                "response_format": {"type": "json_object"},
            }
            response: dict[str, Any] | None = None
            try:
                response = request_completion(api_key, payload, event_log, call_id)
                content = extract_content(response)
                validation = validate_judge_json(content)
                save_call(run_dir, call_id, payload, response, content, validation)
                judge_results.append(
                    {
                        "call_id": call_id,
                        "requested_model": model,
                        "returned_model": response.get("model"),
                        "input_source": judge_input_source,
                        **validation,
                    }
                )
            except Exception as exc:
                save_call(run_dir, call_id, payload, response, None, fatal_error=str(exc))
                judge_results.append(
                    {
                        "call_id": call_id,
                        "requested_model": model,
                        "input_source": judge_input_source,
                        "parse_valid": False,
                        "schema_valid": False,
                        "failure_reasons": [f"FATAL_API_ERROR: {exc}"],
                    }
                )

    valid_count = sum(item["schema_valid"] for item in judge_results)
    summary = {
        "completed_at_utc": utc_now(),
        "run_directory": str(run_dir),
        "pretender_calls_completed": len(pretender_outputs),
        "pretender_failures": pretender_failures,
        "judge_input_source": judge_input_source,
        "judge_calls_attempted": len(judge_results),
        "judge_schema_valid": valid_count,
        "judge_schema_total": len(judge_results),
        "judge_access_probe_passed": valid_count == 6,
        "full_q0_gate_passed": (
            len(pretender_outputs) == 2
            and judge_input_source == "live_naive_pretender_output"
            and valid_count == 6
        ),
        "judge_results": judge_results,
    }
    (run_dir / "summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print(f"Results saved to: {run_dir.resolve()}")
    return 0 if summary["full_q0_gate_passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
